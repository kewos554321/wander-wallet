function serialize(node: IconNode): string {
  return node
    .map(([tag, attrs]) => {
      const serialized = Object.entries(attrs)
        .map(([key, value]) => `${key}="${value}"`)
        .join(" ")
      return `<${tag} ${serialized} />`
    })
    .join("")
}

/** Inline SVG markup for a category pin/popup (Leaflet renders HTML, not React). */
export function categoryPinIconSvg(
  category: string | null,
  { size, color, strokeWidth = 2 }: { size: number; color: string; strokeWidth?: number },
): string {
  const key: ExpenseCategory = category && category in PIN_ICON_NODES ? (category as ExpenseCategory) : "other"
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${serialize(PIN_ICON_NODES[key])}</svg>`
}
